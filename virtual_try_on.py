@app.route('/generate', methods=['POST'])
def generate():
    try:
        # Check if files are present
        if 'personImage' not in request.files or 'costumeImage' not in request.files:
            return jsonify({'error': 'Both images are required'}), 400

        person_image = request.files['personImage']
        costume_image = request.files['costumeImage']

        if person_image.filename == '' or costume_image.filename == '':
            return jsonify({'error': 'Both images must be selected'}), 400

        # Read the file contents once
        person_image_bytes = person_image.read()
        costume_image_bytes = costume_image.read()

        # Generate the image
        output_path = generate_dress_change(
            person_image_bytes,
            person_image.filename,
            costume_image_bytes,
            costume_image.filename
        )

        # Read the generated image and convert to base64
        with open(output_path, 'rb') as f:
            image_data = base64.b64encode(f.read()).decode('utf-8')

        return jsonify({
            'success': True,
            'image': f'data:image/jpeg;base64,{image_data}',
            'filename': os.path.basename(output_path)
        })

    except Exception as e:
        return jsonify({'error': str(e)}), 500


